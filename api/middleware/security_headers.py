"""
Security-header injection for every outgoing response.

Adds two defensive headers identified by the API Sentinel transport-layer
audit as missing on the Railway-hosted API origin:

  - Strict-Transport-Security: max-age=31536000; includeSubDomains
    Tells browsers to refuse HTTP for one year on this host and any
    subdomain. Cached in browser memory; once seen, every subsequent
    visit auto-upgrades to HTTPS before the request leaves the machine,
    closing the SSL-strip window that a passive attacker could exploit
    on a misconfigured initial request.

  - X-Content-Type-Options: nosniff
    Tells browsers to trust the server's Content-Type and never
    second-guess via MIME sniffing. Defends against an exotic class of
    attacks where a JSON response is reinterpreted as HTML and executed.

WHY PURE-ASGI INSTEAD OF @app.middleware("http"):

A decorator-style middleware only sees responses generated by the route
layer. It misses responses generated by middleware itself — CORS
preflight 204s, RateLimitMiddleware's 429s, LockdownMiddleware's 503s,
CatchUnhandledExceptionsMiddleware's 500s, Starlette's 404s. We want
HSTS on every single outgoing response, including those, because the
browser caches HSTS from any response on the origin.

A pure-ASGI class that wraps the inner app's `send` callable injects
headers on the `http.response.start` message regardless of who
produced the response. That's the only correct place to do this.

MIDDLEWARE ORDERING:

This module is added LAST in api/main.py (which means OUTERMOST after
Starlette's add_middleware prepend), so every response — including
CORSMiddleware's preflight responses, which CORS handles internally
without invoking the inner chain — passes through this layer on the way
out. Putting it inside CORS would miss those preflight responses, which
is a small but real correctness gap.

HSTS IS HTTPS-ONLY PER RFC 6797:

RFC 6797 section 7.2 explicitly forbids sending HSTS over plain HTTP:

  > An HSTS Host MUST NOT include the STS header field in HTTP responses
  > conveyed over non-secure transport.

Browsers ignore HSTS over HTTP anyway, so violating this is harmless in
practice — but it's lazy, would re-trigger the same API Sentinel audit
finding on any non-HTTPS endpoint, and leaks a misleading header during
local dev. We honor the prohibition by checking X-Forwarded-Proto
(Railway's edge proxy sets this to "https" for TLS requests) before
emitting HSTS. Local dev with no proxy correctly skips HSTS.

X-Content-Type-Options has no such restriction — emitted on every
response regardless of transport.
"""
from collections.abc import Iterable

HSTS_VALUE = b"max-age=31536000; includeSubDomains"
NOSNIFF_VALUE = b"nosniff"


def _is_https_request(scope: dict) -> bool:
    """
    Decide whether the inbound request was carried over HTTPS.

    Order of precedence:
      1. X-Forwarded-Proto header — Railway's edge proxy sets this to
         "https" when the original request used TLS. The header may be
         a comma-separated chain in some multi-proxy topologies; we use
         the leftmost entry because it is what the outermost trusted
         proxy observed (same trust model as get_client_ip).
      2. scope["scheme"] — set by the ASGI server (uvicorn) when the app
         is fronted by TLS directly, e.g. local dev with `uvicorn --ssl-...`.
         In production on Railway this is always "http" because TLS is
         terminated at the edge and the request reaches us in plaintext.

    Returns False when no proxy header is present and the ASGI scheme is
    "http" — the local-dev default, which correctly suppresses HSTS.
    """
    for name, value in scope.get("headers", []):
        if name == b"x-forwarded-proto":
            leftmost = value.split(b",", 1)[0].strip().lower()
            return leftmost == b"https"
    return scope.get("scheme", "").lower() == "https"


def _add_or_replace(headers: list, name: bytes, value: bytes) -> list:
    """
    Append (name, value) to a header list, dropping any existing entry
    with the same name first. Avoids duplicate emission if an inner
    handler somehow set the same header.
    """
    name_lower = name.lower()
    filtered = [(n, v) for n, v in headers if n.lower() != name_lower]
    filtered.append((name, value))
    return filtered


class SecurityHeadersMiddleware:
    """
    Pure-ASGI middleware that appends security headers to every outgoing
    response. Lifestyle modeled on CatchUnhandledExceptionsMiddleware in
    api/main.py — both use the wrap-send pattern for the same reason
    (reach responses produced anywhere in the stack).
    """

    def __init__(self, app):
        self.app = app

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            await self.app(scope, receive, send)
            return

        is_https = _is_https_request(scope)

        async def _send(message):
            if message["type"] == "http.response.start":
                headers: Iterable = message.get("headers", [])
                headers = list(headers)
                headers = _add_or_replace(headers, b"x-content-type-options", NOSNIFF_VALUE)
                if is_https:
                    headers = _add_or_replace(
                        headers, b"strict-transport-security", HSTS_VALUE
                    )
                message["headers"] = headers
            await send(message)

        await self.app(scope, receive, _send)
